"""Reduce only the TV splash bitrate; copy every later frame and all audio.

Requires ffmpeg/ffprobe and the checked-in v99 opening and v104 continuous tour.
No font or image regeneration: Golden Rules and safety labels stay byte-identical.
"""
import json
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / 'assets/tv-v104/tour.mp4'
OUT = ROOT / 'assets/tv-v112'
OUT.mkdir(parents=True, exist_ok=True)
manifest_path = ROOT / 'tv-media-timeline.js'
manifest = json.loads(manifest_path.read_text().split(' = ', 1)[1].rstrip(';\n'))
duration = manifest['segments'][0]['end']
# v104 was muxed from millisecond MKV timestamps. Keep its first weather
# keyframe at 8.167s instead of rounding it back to the ideal 245/30 boundary.
boundary = round(duration, 3)


def run(args):
    subprocess.run(['ffmpeg', '-hide_banner', '-loglevel', 'error', '-y', *args], check=True)


with tempfile.TemporaryDirectory(prefix='power-tbm-opening-') as directory:
    work = Path(directory)
    run(['-i', str(ROOT / 'assets/tv-v99/00-opening.mp4'), '-an',
         '-vf', f'fps=30,tpad=stop_mode=clone:stop_duration=1,trim=duration={duration},'
                'setpts=PTS-STARTPTS,scale=480:1040:force_original_aspect_ratio=increase,'
                'crop=480:1040,setsar=1',
         '-t', str(duration), '-r', '30', '-c:v', 'libx264', '-preset', 'fast',
         '-crf', '24', '-maxrate', '900k', '-bufsize', '900k',
         '-profile:v', 'main', '-level:v', '3.1', '-pix_fmt', 'yuv420p',
         '-g', '60', '-threads', '2', str(work / 'opening.mkv')])
    # Match the base MP4's time base before concatenation. Keep one constant
    # frame size/profile and the original AAC priming across every voice change.
    run(['-i', str(work / 'opening.mkv'), '-c', 'copy', '-video_track_timescale', '16000',
         str(work / 'opening.mp4')])
    (work / 'concat.txt').write_text(
        f"file '{work / 'opening.mp4'}'\nduration {boundary}\n"
        f"file '{BASE}'\ninpoint {boundary}\n", encoding='utf-8')
    run(['-copyts', '-f', 'concat', '-safe', '0', '-i', str(work / 'concat.txt'),
         '-i', str(BASE), '-map', '0:v:0', '-map', '1:a:0', '-c', 'copy',
         '-movflags', '+faststart', str(OUT / 'tour.mp4')])

manifest['src'] = 'assets/tv-v112/tour.mp4'
manifest_path.write_text(
    '// Generated by scripts/build-tv-opening.py; times are in seconds.\n'
    'window.PowerTBMTVTimeline = ' + json.dumps(manifest, indent=2) + ';\n', encoding='utf-8')
(OUT / 'README.txt').write_text(
    'TV opening bitrate optimization of ../tv-v104/tour.mp4.\n'
    'Opening: CRF 24, 900 kbps VBV maxrate/buffer; all 245 frames at 480x1040/30 fps.\n'
    'Every later video packet and the entire AAC track are copied without re-encoding.\n'
    'Original timestamps, chapter timing, Golden Rules and full safety ending retained.\n'
    'Rebuild: python3 scripts/build-tv-opening.py\n'
    'Verify: python3 tests/verify-tv-media.py\n'
    'Music license: ../audio/BGM_CREDITS.txt\n', encoding='utf-8')
print(f'Continuous tour: {(OUT / "tour.mp4").stat().st_size:,} bytes', flush=True)
