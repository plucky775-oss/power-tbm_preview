"""Pack the moving backdrop and phone into ONE continuous H.264/AAC stream.

The TV draws two rectangles from one decoder; it never starts a second player.
Keep v112 chapter times, all 30 fps phone frames and the AAC packets unchanged.
Requires ffmpeg/ffprobe. Original source assets are never modified.
"""
import json
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'assets/tv-v116'
OUT.mkdir(parents=True, exist_ok=True)
manifest_path = ROOT / 'tv-media-timeline.js'
manifest = json.loads(manifest_path.read_text().split(' = ', 1)[1].rstrip(';\n'))
BASE = ROOT / 'assets/tv-v112/tour.mp4'
BACKGROUNDS = {
    'intro': 'power-tbm-lightning-opening-v62.webp',
    'weather': 'weather-powerlines-v60.mp4',
    'meeting': 'tablet-review-v63.mp4',
    'support': 'field-tools-kepco-v68.mp4',
    'emergency': 'emergency-response-changwon119-v66.mp4',
    'safety': 'tablet-review-v63.mp4',
    'closing': 'tbm-guide-closing-v69.mp4',
}


def run(args):
    subprocess.run(['ffmpeg', '-hide_banner', '-loglevel', 'error', '-y',
                    '-filter_complex_threads', '1', *args], check=True)


with tempfile.TemporaryDirectory(prefix='tbm-one-stream-') as directory:
    work = Path(directory)
    concat = []
    for entry in manifest['segments']:
        key = 'emergency' if entry['id'] == '05-emergency' else entry['page']
        source = ROOT / 'assets/background' / BACKGROUNDS[key]
        frames = round(entry['duration'] * 30)
        args = ['-loop', '1', '-framerate', '15'] if source.suffix == '.webp' else ['-stream_loop', '-1']
        target = work / (entry['id'] + '.mp4')
        run(args + ['-i', str(source), '-an', '-vf',
                    'fps=15,scale=320:180:force_original_aspect_ratio=increase,crop=320:180,setsar=1,fps=30',
                    '-frames:v', str(frames), '-c:v', 'libx264', '-preset', 'fast', '-crf', '18',
                    '-threads', '2', '-pix_fmt', 'yuv420p', '-video_track_timescale', '15360', str(target)])
        concat.append(f"file '{target}'")
        print(f"Backdrop {entry['id']}: {frames} frames", flush=True)
    (work / 'concat.txt').write_text('\n'.join(concat), encoding='utf-8')
    run(['-f', 'concat', '-safe', '0', '-i', str(work / 'concat.txt'), '-c', 'copy', str(work / 'backdrops.mp4')])
    # 30 * 77 macroblocks * 30 fps fits H.264 level 3.1. The unused strip is
    # black and compresses cheaply. Never rescale the existing 480x1040 phone.
    run(['-i', str(BASE), '-i', str(work / 'backdrops.mp4'), '-filter_complex',
         '[0:v]fps=30,setpts=N/(30*TB),pad=480:1232:0:192:black[phone];'
         '[1:v]setpts=N/(30*TB)[bg];[phone][bg]overlay=0:0:shortest=1,addroi=x=0:y=0:w=320:h=180:qoffset=0.2,setsar=1[v]',
         '-map', '[v]', '-frames:v', str(round(manifest['duration'] * 30)),
         '-c:v', 'libx264', '-preset', 'slow', '-crf', '25', '-maxrate', '700k', '-bufsize', '350k',
         '-profile:v', 'main', '-level:v', '3.1', '-pix_fmt', 'yuv420p', '-g', '60', '-threads', '2',
         '-an', str(work / 'picture.mp4')])
    # Mux separately: -frames:v can otherwise stop the final partial AAC packet.
    run(['-i', str(work / 'picture.mp4'), '-i', str(BASE), '-map', '0:v:0', '-map', '1:a:0',
         '-c', 'copy', '-movflags', '+faststart', str(OUT / 'tour.mp4')])

manifest.update(src='assets/tv-v116/tour.mp4', width=480, height=1232,
                surfaces={'background': [0, 0, 320, 180], 'phone': [0, 192, 480, 1040]})
manifest_path.write_text('// Generated by scripts/build-tv-background.py; times are in seconds.\n'
                         'window.PowerTBMTVTimeline = ' + json.dumps(manifest, indent=2) + ';\n', encoding='utf-8')
(OUT / 'README.txt').write_text(
    'Single H.264 Main 3.1 / AAC stream, 480x1232, 30 fps.\n'
    'Backdrop: 0,0,320,180 (15 unique frames/sec); phone: 0,192,480,1040 (30 fps).\n'
    'Continuous AAC track copied unchanged from v112. All chapters and safety ending retained.\n'
    'Background/phone canvases share ONE video decoder and clock.\n'
    'Rebuild: python3 scripts/build-tv-background.py\n'
    'Music license: ../audio/BGM_CREDITS.txt\n', encoding='utf-8')
print(f"Single stream: {(OUT / 'tour.mp4').stat().st_size:,} bytes", flush=True)
